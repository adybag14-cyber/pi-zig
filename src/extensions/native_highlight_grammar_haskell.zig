const b = @import("native_highlight_lazy_batch3_values.zig");
pub fn create(e: *b.Engine) !b.c.JSValue {
    return b.factory(e, "haskell", build);
}
pub fn build(e: *b.Engine, h: b.c.JSValue) !b.c.JSValue {
    var s: b.Scope = .{ .engine = e };
    defer s.deinit();
    const comment = try s.object();
    const c1 = try s.get(h, "COMMENT");
    const b1 = try s.text("--");
    const e1 = try s.text("$");
    const variants = try b.list(&s, &.{try s.call(c1, h, &.{ b1, e1 })});
    const c2 = try s.get(h, "COMMENT");
    const b2 = try b.rx(&s, "\\{-");
    const e2 = try b.rx(&s, "-\\}");
    const opt = try s.object();
    try s.put(opt, "contains", try b.list(&s, &.{try s.text("self")}));
    try s.index(variants, 1, try s.call(c2, h, &.{ b2, e2, opt }));
    try s.put(comment, "variants", variants);
    const pragma = try b.mode(&s, "meta");
    try s.put(pragma, "begin", try b.rx(&s, "\\{-#"));
    try s.put(pragma, "end", try b.rx(&s, "#-\\}"));
    const pre = try b.mode(&s, "meta");
    try s.put(pre, "begin", try s.text("^#"));
    try s.put(pre, "end", try s.text("$"));
    const constructor = try b.mode(&s, "type");
    try s.put(constructor, "begin", try s.text("\\b[A-Z][\\w']*"));
    try s.put(constructor, "relevance", b.c.JS_NewInt32(e.context, 0));
    const list = try s.object();
    try s.put(list, "begin", try s.text("\\("));
    try s.put(list, "end", try s.text("\\)"));
    try s.put(list, "illegal", try s.text("\""));
    const typename = try b.mode(&s, "type");
    try s.put(typename, "begin", try s.text("\\b[A-Z][\\w]*(\\((\\.\\.|,|\\w+)\\))?"));
    const lc = try b.list(&s, &.{ pragma, pre, typename });
    const inherit = try s.get(h, "inherit");
    const title = try s.get(h, "TITLE_MODE");
    const changes = try s.object();
    try s.put(changes, "begin", try s.text("[_a-z][\\w']*"));
    try s.index(lc, 3, try s.call(inherit, h, &.{ title, changes }));
    try s.index(lc, 4, comment);
    try s.put(list, "contains", lc);
    const record = try s.object();
    try s.put(record, "begin", try b.rx(&s, "\\{"));
    try s.put(record, "end", try b.rx(&s, "\\}"));
    try s.put(record, "contains", try s.get(list, "contains"));
    const l = try s.object();
    try s.put(l, "name", try s.text("Haskell"));
    try s.put(l, "aliases", try b.list(&s, &.{try s.text("hs")}));
    try s.put(l, "keywords", try s.text(source_text));
    const a = try s.array();
    const module = try s.object();
    try s.put(module, "beginKeywords", try s.text("module"));
    try s.put(module, "end", try s.text("where"));
    try s.put(module, "keywords", try s.text("module where"));
    try s.put(module, "contains", try b.list(&s, &.{ list, comment }));
    try s.put(module, "illegal", try s.text("\\W\\.|;"));
    try s.index(a, 0, module);
    const imp = try s.object();
    try s.put(imp, "begin", try s.text("\\bimport\\b"));
    try s.put(imp, "end", try s.text("$"));
    try s.put(imp, "keywords", try s.text("import qualified as hiding"));
    try s.put(imp, "contains", try b.list(&s, &.{ list, comment }));
    try s.put(imp, "illegal", try s.text("\\W\\.|;"));
    try s.index(a, 1, imp);
    const cls = try b.mode(&s, "class");
    try s.put(cls, "begin", try s.text("^(\\s*)?(class|instance)\\b"));
    try s.put(cls, "end", try s.text("where"));
    try s.put(cls, "keywords", try s.text("class family instance where"));
    try s.put(cls, "contains", try b.list(&s, &.{ constructor, list, comment }));
    try s.index(a, 2, cls);
    const data = try b.mode(&s, "class");
    try s.put(data, "begin", try s.text("\\b(data|(new)?type)\\b"));
    try s.put(data, "end", try s.text("$"));
    try s.put(data, "keywords", try s.text("data family type newtype deriving"));
    try s.put(data, "contains", try b.list(&s, &.{ pragma, constructor, list, record, comment }));
    try s.index(a, 3, data);
    const default = try s.object();
    try s.put(default, "beginKeywords", try s.text("default"));
    try s.put(default, "end", try s.text("$"));
    try s.put(default, "contains", try b.list(&s, &.{ constructor, list, comment }));
    try s.index(a, 4, default);
    const infix = try s.object();
    try s.put(infix, "beginKeywords", try s.text("infix infixl infixr"));
    try s.put(infix, "end", try s.text("$"));
    try s.put(infix, "contains", try b.list(&s, &.{ try s.get(h, "C_NUMBER_MODE"), comment }));
    try s.index(a, 5, infix);
    const foreign = try s.object();
    try s.put(foreign, "begin", try s.text("\\bforeign\\b"));
    try s.put(foreign, "end", try s.text("$"));
    try s.put(foreign, "keywords", try s.text("foreign import export ccall stdcall cplusplus jvm dotnet safe unsafe"));
    try s.put(foreign, "contains", try b.list(&s, &.{ constructor, try s.get(h, "QUOTE_STRING_MODE"), comment }));
    try s.index(a, 6, foreign);
    const shebang = try b.mode(&s, "meta");
    try s.put(shebang, "begin", try s.text("#!\\/usr\\/bin\\/env runhaskell"));
    try s.put(shebang, "end", try s.text("$"));
    try s.index(a, 7, shebang);
    try s.index(a, 8, pragma);
    try s.index(a, 9, pre);
    try s.index(a, 10, try s.get(h, "QUOTE_STRING_MODE"));
    try s.index(a, 11, try s.get(h, "C_NUMBER_MODE"));
    try s.index(a, 12, constructor);
    const i2 = try s.get(h, "inherit");
    const t2 = try s.get(h, "TITLE_MODE");
    const o2 = try s.object();
    try s.put(o2, "begin", try s.text("^[_a-z][\\w']*"));
    try s.index(a, 13, try s.call(i2, h, &.{ t2, o2 }));
    try s.index(a, 14, comment);
    const booster = try s.object();
    try s.put(booster, "begin", try s.text("->|<-"));
    try s.index(a, 15, booster);
    try s.put(l, "contains", a);
    return b.c.JS_DupValue(e.context, l);
}
