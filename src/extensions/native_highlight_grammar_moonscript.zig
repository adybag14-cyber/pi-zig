pub fn build(e: *b.Engine, h: b.c.JSValue) !b.c.JSValue {
    var s: b.Scope = .{ .engine = e };
    defer s.deinit();
    const kw = try s.object();
    try s.put(kw, "keyword", try s.text(source_keyword));
    try s.put(kw, "literal", try s.text(source_literal));
    try s.put(kw, "built_in", try s.text(source_built_in));
    const subst = try b.mode(&s, "subst");
    try s.put(subst, "begin", try b.rx(&s, "#\\{"));
    try s.put(subst, "end", try b.rx(&s, "\\}"));
    try s.put(subst, "keywords", kw);
    const expressions = try s.array();
    const inherit = try s.get(h, "inherit");
    const num = try s.get(h, "C_NUMBER_MODE");
    const opt = try s.object();
    const starts = try s.object();
    try s.put(starts, "end", try s.text("(\\s*/)?"));
    try s.put(starts, "relevance", b.c.JS_NewInt32(e.context, 0));
    try s.put(opt, "starts", starts);
    try s.index(expressions, 0, try s.call(inherit, h, &.{ num, opt }));
    const str = try b.mode(&s, "string");
    const sq = try s.object();
    try s.put(sq, "begin", try b.rx(&s, "'"));
    try s.put(sq, "end", try b.rx(&s, "'"));
    try s.put(sq, "contains", try b.list(&s, &.{try s.get(h, "BACKSLASH_ESCAPE")}));
    const dq = try s.object();
    try s.put(dq, "begin", try b.rx(&s, "\""));
    try s.put(dq, "end", try b.rx(&s, "\""));
    try s.put(dq, "contains", try b.list(&s, &.{ try s.get(h, "BACKSLASH_ESCAPE"), subst }));
    try s.put(str, "variants", try b.list(&s, &.{ sq, dq }));
    try s.index(expressions, 1, str);
    const builtin = try b.mode(&s, "built_in");
    try s.put(builtin, "begin", try s.concat(try s.text("@__"), try s.get(h, "IDENT_RE")));
    try s.index(expressions, 2, builtin);
    const instance = try s.object();
