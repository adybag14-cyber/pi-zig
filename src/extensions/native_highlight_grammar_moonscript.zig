    try s.put(anon, "relevance", b.c.JS_NewInt32(e.context, 0));
    const af = try b.mode(&s, "function");
    try s.put(af, "begin", try s.text(possible));
    try s.put(af, "end", try s.text("[-=]>"));
    try s.put(af, "returnBegin", b.boolean(&s, true));
    try s.put(af, "contains", try b.list(&s, &.{params}));
    try s.put(anon, "contains", try b.list(&s, &.{af}));
    try s.index(extra, 2, anon);
    const cls = try b.mode(&s, "class");
    try s.put(cls, "beginKeywords", try s.text("class"));
    try s.put(cls, "end", try s.text("$"));
    try s.put(cls, "illegal", try b.rx(&s, "[:=\"\\[\\]]"));
    const ext = try s.object();
    try s.put(ext, "beginKeywords", try s.text("extends"));
    try s.put(ext, "endsWithParent", b.boolean(&s, true));
    try s.put(ext, "illegal", try b.rx(&s, "[:=\"\\[\\]]"));
    try s.put(ext, "contains", try b.list(&s, &.{title}));
    try s.put(cls, "contains", try b.list(&s, &.{ ext, title }));
    try s.index(extra, 3, cls);
    const name = try b.mode(&s, "name");
    try s.put(name, "begin", try s.text("[A-Za-z$_][0-9A-Za-z$_]*:"));
    try s.put(name, "end", try s.text(":"));
    try s.put(name, "returnBegin", b.boolean(&s, true));
    try s.put(name, "returnEnd", b.boolean(&s, true));
    try s.put(name, "relevance", b.c.JS_NewInt32(e.context, 0));
    try s.index(extra, 4, name);
    try s.put(l, "contains", try s.call(concat, expressions, &.{extra}));
    return b.c.JS_DupValue(e.context, l);
}
