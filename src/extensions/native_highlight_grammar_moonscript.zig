    try s.put(params, "begin", try s.text("\\([^\\(]"));
    try s.put(params, "returnBegin", b.boolean(&s, true));
    const paren = try s.object();
    try s.put(paren, "begin", try b.rx(&s, "\\("));
    try s.put(paren, "end", try b.rx(&s, "\\)"));
    try s.put(paren, "keywords", kw);
    try s.put(paren, "contains", try s.invoke(try b.list(&s, &.{try s.text("self")}), "concat", &.{expressions}));
    try s.put(params, "contains", try b.list(&s, &.{paren}));
    const l = try s.object();
