//! Actual highlight.js 10.7.3 static keyword inputs; native factory follows.
const b = @import("native_highlight_lazy_batch3_values.zig");
pub fn create(e: *b.Engine) !b.c.JSValue {
    return b.factory(e, "puppet", build);
}
pub fn build(e: *b.Engine, h: b.c.JSValue) !b.c.JSValue {
    var s: b.Scope = .{ .engine = e };
    defer s.deinit();
    const kw = try s.object();
    try s.put(kw, "keyword", try s.text(source_keyword));
    try s.put(kw, "literal", try s.text(source_literal));
    try s.put(kw, "built_in", try s.text(source_built_in));
    const cf = try s.get(h, "COMMENT");
    const cb = try s.text("#");
    const ce = try s.text("$");
    const comment = try s.call(cf, h, &.{ cb, ce });
    const ident = "([A-Za-z_]|::)(\\w|::)*";
    const inherit = try s.get(h, "inherit");
    const tm = try s.get(h, "TITLE_MODE");
    const opt = try s.object();
    try s.put(opt, "begin", try s.text(ident));
    const title = try s.call(inherit, h, &.{ tm, opt });
    const variable = try b.mode(&s, "variable");
    try s.put(variable, "begin", try s.text("\\$" ++ ident));
    const str = try b.mode(&s, "string");
    try s.put(str, "contains", try b.list(&s, &.{ try s.get(h, "BACKSLASH_ESCAPE"), variable }));
    const sv = try s.array();
    for ([_][]const u8{ "'", "\"" }, 0..) |p, i| {
        const m = try s.object();
        try s.put(m, "begin", try b.rx(&s, p));
        try s.put(m, "end", try b.rx(&s, p));
        try s.index(sv, @intCast(i), m);
    }
    try s.put(str, "variants", sv);
    const l = try s.object();
    try s.put(l, "name", try s.text("Puppet"));
    try s.put(l, "aliases", try b.list(&s, &.{try s.text("pp")}));
    const a = try b.list(&s, &.{ comment, variable, str });
    const cls = try s.object();
    try s.put(cls, "beginKeywords", try s.text("class"));
    try s.put(cls, "end", try s.text("\\{|;"));
    try s.put(cls, "illegal", try b.rx(&s, "="));
    try s.put(cls, "contains", try b.list(&s, &.{ title, comment }));
    try s.index(a, 3, cls);
    const define = try s.object();
    try s.put(define, "beginKeywords", try s.text("define"));
    try s.put(define, "end", try b.rx(&s, "\\{"));
    const section = try b.mode(&s, "section");
    try s.put(section, "begin", try s.get(h, "IDENT_RE"));
    try s.put(section, "endsParent", b.boolean(&s, true));
    try s.put(define, "contains", try b.list(&s, &.{section}));
    try s.index(a, 4, define);
    const resource = try s.object();
    try s.put(resource, "begin", try s.concat(try s.get(h, "IDENT_RE"), try s.text("\\s+\\{")));
    try s.put(resource, "returnBegin", b.boolean(&s, true));
    try s.put(resource, "end", try b.rx(&s, "\\S"));
    const keyword = try b.mode(&s, "keyword");
    try s.put(keyword, "begin", try s.get(h, "IDENT_RE"));
    const brace = try s.object();
    try s.put(brace, "begin", try b.rx(&s, "\\{"));
    try s.put(brace, "end", try b.rx(&s, "\\}"));
    try s.put(brace, "keywords", kw);
    try s.put(brace, "relevance", b.c.JS_NewInt32(e.context, 0));
    const bc = try b.list(&s, &.{ str, comment });
    const assignment = try s.object();
    try s.put(assignment, "begin", try s.text("[a-zA-Z_]+\\s*=>"));
    try s.put(assignment, "returnBegin", b.boolean(&s, true));
    try s.put(assignment, "end", try s.text("=>"));
    const attr = try b.mode(&s, "attr");
    try s.put(attr, "begin", try s.get(h, "IDENT_RE"));
    try s.put(assignment, "contains", try b.list(&s, &.{attr}));
    try s.index(bc, 2, assignment);
    const num = try b.mode(&s, "number");
    try s.put(num, "begin", try s.text("(\\b0[0-7_]+)|(\\b0x[0-9a-fA-F_]+)|(\\b[1-9][0-9_]*(\\.[0-9_]+)?)|[0_]\\b"));
    try s.put(num, "relevance", b.c.JS_NewInt32(e.context, 0));
    try s.index(bc, 3, num);
    try s.index(bc, 4, variable);
    try s.put(brace, "contains", bc);
    try s.put(resource, "contains", try b.list(&s, &.{ keyword, brace }));
    try s.put(resource, "relevance", b.c.JS_NewInt32(e.context, 0));
    try s.index(a, 5, resource);
    try s.put(l, "contains", a);
    return b.c.JS_DupValue(e.context, l);
}
