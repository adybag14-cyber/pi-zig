//! Actual highlight.js10.7.3 Lisp factory; unqualified source.
const b = @import("native_highlight_lazy_batch3_values.zig");
pub fn create(e: *b.Engine) !b.c.JSValue {
    return b.factory(e, "lisp", build);
}
pub fn build(e: *b.Engine, hljs: b.c.JSValue) !b.c.JSValue {
    var s: b.Scope = .{ .engine = e };
    defer s.deinit();
    const ident_re = "[a-zA-Z_\\-+\\*\\/<=>&#][a-zA-Z0-9_\\-+*\\/<=>&#!]*";
    const mec_re = "\\|[^]*?\\|";
    const number_re = "(-|\\+)?\\d+(\\.\\d+|\\/\\d+)?((d|e|f|l|s|D|E|F|L|S)(\\+|-)?\\d+)?";
    const literal = try b.mode(&s, "literal");
    try s.put(literal, "begin", try s.text("\\b(t{1}|nil)\\b"));
    const number = try b.mode(&s, "number");
    const variants = try s.array();
    const simple = try s.object();
    try s.put(simple, "begin", try s.text(number_re));
    try s.put(simple, "relevance", b.c.JS_NewInt32(e.context, 0));
    try s.index(variants, 0, simple);
    inline for (.{ "#(b|B)[0-1]+(/[0-1]+)?", "#(o|O)[0-7]+(/[0-7]+)?", "#(x|X)[0-9a-fA-F]+(/[0-9a-fA-F]+)?" }, 0..) |pattern, index| {
        const variant = try s.object();
        try s.put(variant, "begin", try s.text(pattern));
        try s.index(variants, @intCast(index + 1), variant);
    }
    const complex = try s.object();
    try s.put(complex, "begin", try s.text("#(c|C)\\(" ++ number_re ++ " +" ++ number_re));
    try s.put(complex, "end", try s.text("\\)"));
    try s.index(variants, 4, complex);
    try s.put(number, "variants", variants);
    const inherit = try s.get(hljs, "inherit");
    const quote = try s.get(hljs, "QUOTE_STRING_MODE");
    const changes = try s.object();
    try s.put(changes, "illegal", b.c.pi_js_null());
    const string = try s.call(inherit, hljs, &.{ quote, changes });
    const comment_function = try s.get(hljs, "COMMENT");
    const options = try s.object();
    try s.put(options, "relevance", b.c.JS_NewInt32(e.context, 0));
    const comment = try s.call(comment_function, hljs, &.{ try s.text(";"), try s.text("$"), options });
    const variable = try s.object();
    try s.put(variable, "begin", try s.text("\\*"));
    try s.put(variable, "end", try s.text("\\*"));
    const keyword = try b.mode(&s, "symbol");
    try s.put(keyword, "begin", try s.text("[:&]" ++ ident_re));
    const ident = try s.object();
    try s.put(ident, "begin", try s.text(ident_re));
    try s.put(ident, "relevance", b.c.JS_NewInt32(e.context, 0));
    const mec = try s.object();
    try s.put(mec, "begin", try s.text(mec_re));
    const quoted_list = try s.object();
    try s.put(quoted_list, "begin", try s.text("\\("));
    try s.put(quoted_list, "end", try s.text("\\)"));
    try s.put(quoted_list, "contains", try b.list(&s, &.{ try s.text("self"), literal, string, number, ident }));
    const quoted = try s.object();
    try s.put(quoted, "contains", try b.list(&s, &.{ number, string, variable, keyword, quoted_list, ident }));
    const quoted_parens = try s.object();
    try s.put(quoted_parens, "begin", try s.text("['`]\\("));
    try s.put(quoted_parens, "end", try s.text("\\)"));
    const quote_form = try s.object();
    try s.put(quote_form, "begin", try s.text("\\(quote "));
    try s.put(quote_form, "end", try s.text("\\)"));
    const quote_words = try s.object();
    try s.put(quote_words, "name", try s.text("quote"));
    try s.put(quote_form, "keywords", quote_words);
    const quoted_mec = try s.object();
    try s.put(quoted_mec, "begin", try s.text("'" ++ mec_re));
    try s.put(quoted, "variants", try b.list(&s, &.{ quoted_parens, quote_form, quoted_mec }));
    const atom = try s.object();
    const plain_atom = try s.object();
    try s.put(plain_atom, "begin", try s.text("'" ++ ident_re));
    const function_atom = try s.object();
    try s.put(function_atom, "begin", try s.text("#'" ++ ident_re ++ "(::" ++ ident_re ++ ")*"));
    try s.put(atom, "variants", try b.list(&s, &.{ plain_atom, function_atom }));
    const list = try s.object();
    try s.put(list, "begin", try s.text("\\(\\s*"));
    try s.put(list, "end", try s.text("\\)"));
    const body = try s.object();
    try s.put(body, "endsWithParent", b.boolean(&s, true));
    try s.put(body, "relevance", b.c.JS_NewInt32(e.context, 0));
    const name = try b.mode(&s, "name");
    const normal_name = try s.object();
    try s.put(normal_name, "begin", try s.text(ident_re));
    try s.put(normal_name, "relevance", b.c.JS_NewInt32(e.context, 0));
    const quoted_name = try s.object();
    try s.put(quoted_name, "begin", try s.text(mec_re));
    try s.put(name, "variants", try b.list(&s, &.{ normal_name, quoted_name }));
    try s.set(list, "contains", try b.list(&s, &.{ name, body }));
    try s.set(body, "contains", try b.list(&s, &.{ quoted, atom, list, literal, number, string, comment, variable, keyword, mec, ident }));
    const language = try s.object();
    try s.put(language, "name", try s.text("Lisp"));
    try s.put(language, "illegal", try b.rx(&s, "\\S"));
    const shebang = try s.get(hljs, "SHEBANG");
    try s.put(language, "contains", try b.list(&s, &.{ number, try s.call(shebang, hljs, &.{}), literal, string, comment, quoted, atom, list, ident }));
    return b.c.JS_DupValue(e.context, language);
}
