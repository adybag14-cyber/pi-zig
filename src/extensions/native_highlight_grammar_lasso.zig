    const code = try b.list(&s, &.{ try s.get(h, "C_LINE_COMMENT_MODE"), try s.get(h, "C_BLOCK_COMMENT_MODE") });
    const ni = try s.get(h, "inherit");
    const nm = try s.get(h, "C_NUMBER_MODE");
    const no = try s.object();
    try s.put(no, "begin", try s.concat(try s.get(h, "C_NUMBER_RE"), try s.text("|(-?infinity|NaN)\\b")));
