//! Actual highlight.js 10.7.3 static keyword inputs; native factory follows.
const b = @import("native_highlight_lazy_batch3_values.zig");
pub fn create(e: *b.Engine) !b.c.JSValue {
    return b.factory(e, "hy", build);
}
pub fn build(e: *b.Engine, h: b.c.JSValue) !b.c.JSValue {
    var s: b.Scope = .{ .engine = e };
    defer s.deinit();
    const pattern = "[a-zA-Z_\\-!.?+*=<>&#'][a-zA-Z_\\-!.?+*=<>&#'0-9/;:]*";
    const kw = try s.object();
    try s.put(kw, "$pattern", try s.text(pattern));
    try s.put(kw, "builtin-name", try s.text(source_builtin_name));
    const symbol = try s.object();
    try s.put(symbol, "begin", try s.text(pattern));
    try s.put(symbol, "relevance", b.c.JS_NewInt32(e.context, 0));
    const num = try b.mode(&s, "number");
    try s.put(num, "begin", try s.text("[-+]?\\d+(\\.\\d+)?"));
    try s.put(num, "relevance", b.c.JS_NewInt32(e.context, 0));
    const inherit = try s.get(h, "inherit");
    const quote = try s.get(h, "QUOTE_STRING_MODE");
    const opt = try s.object();
    try s.put(opt, "illegal", b.c.pi_js_null());
    const str = try s.call(inherit, h, &.{ quote, opt });
    const cf = try s.get(h, "COMMENT");
    const cb = try s.text(";");
    const ce = try s.text("$");
    const co = try s.object();
    try s.put(co, "relevance", b.c.JS_NewInt32(e.context, 0));
    const comment = try s.call(cf, h, &.{ cb, ce, co });
    const literal = try b.mode(&s, "literal");
    try s.put(literal, "begin", try b.rx(&s, "\\b([Tt]rue|[Ff]alse|nil|None)\\b"));
    const collection = try s.object();
    try s.put(collection, "begin", try s.text("[\\[\\{]"));
    try s.put(collection, "end", try s.text("[\\]\\}]"));
    const hint = try b.mode(&s, "comment");
    try s.put(hint, "begin", try s.text("\\^" ++ pattern));
    const hf = try s.get(h, "COMMENT");
    const hb = try s.text("\\^\\{");
    const he = try s.text("\\}");
    const hintcol = try s.call(hf, h, &.{ hb, he });
    const key = try b.mode(&s, "symbol");
    try s.put(key, "begin", try s.text("[:]{1,2}" ++ pattern));
    const list = try s.object();
    try s.put(list, "begin", try s.text("\\("));
    try s.put(list, "end", try s.text("\\)"));
    const body = try s.object();
    try s.put(body, "endsWithParent", b.boolean(&s, true));
    try s.put(body, "relevance", b.c.JS_NewInt32(e.context, 0));
    const name = try b.mode(&s, "name");
    try s.put(name, "relevance", b.c.JS_NewInt32(e.context, 0));
    try s.put(name, "keywords", kw);
    try s.put(name, "begin", try s.text(pattern));
    try s.put(name, "starts", body);
    const all = try b.list(&s, &.{ list, str, hint, hintcol, comment, key, collection, num, literal, symbol });
    const lf = try s.get(h, "COMMENT");
    const lb = try s.text("comment");
    const le = try s.text("");
    try s.set(list, "contains", try b.list(&s, &.{ try s.call(lf, h, &.{ lb, le }), name, body }));
    try s.set(body, "contains", all);
    try s.set(collection, "contains", all);
    const l = try s.object();
    try s.put(l, "name", try s.text("Hy"));
    try s.put(l, "aliases", try b.list(&s, &.{try s.text("hylang")}));
    try s.put(l, "illegal", try b.rx(&s, "\\S"));
    const sf = try s.get(h, "SHEBANG");
    try s.put(l, "contains", try b.list(&s, &.{ try s.call(sf, h, &.{}), list, str, hint, hintcol, comment, key, collection, num, literal }));
    return b.c.JS_DupValue(e.context, l);
}
