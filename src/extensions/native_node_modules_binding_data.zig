//! Selected original Node24.13 modules::BindingData native owner.
//! The target is a real internal binding object with its own template/class.
//! It joins the existing Realm BaseObject FIFO and owns the actual native
//! PackageConfig cache. It is not an AsyncWrap and emits no async hooks.
const std = @import("std");
const a = @import("native_node_argument_values.zig");
const callbacks = @import("native_node_callback_scope.zig");
const native = @import("native_node_async_wrap_state.zig");
const templates = @import("native_node_async_wrap.zig");
const callable = @import("native_node_module_callable.zig");
const package_cache = @import("native_node_package_json_cache.zig");
const package_error = @import("native_node_package_json_error.zig");
const package_values = @import("native_node_package_json_values.zig");
const c = a.c;
pub const Engine = native.Engine;
const Scope = a.Scope;

/// The original internal binding ObjectTemplate has native internal fields.
/// The binding assembler supplies its actual realm Object.prototype. This
/// class is distinct from fs::BindingData and from every AsyncWrap template.
pub const TargetTemplate = struct {
    class_id: c.JSClassID,

    pub fn create(s: *Scope) !TargetTemplate {
        var class_id: c.JSClassID = 0;
        const generation = try s.beforeAllocation();
        if (c.JS_NewClassID(s.engine.runtime, &class_id) == 0)
            return error.OutOfMemory;
        const definition: c.JSClassDef = .{
            .class_name = "modules::BindingData", .finalizer = finalize,
        };
        const status = c.JS_NewClass(s.engine.runtime, class_id, &definition);
        try s.boundary.checkPendingSince(generation);
        if (status < 0) return error.OutOfMemory;
        return .{ .class_id = class_id };
    }
    pub fn newInstance(self: TargetTemplate, s: *Scope,
        actual_object_prototype: c.JSValue) !c.JSValue
    {
        const generation = try s.beforeAllocation();
        return s.checkedAllocation(c.JS_NewObjectProtoClass(s.engine.context,
            actual_object_prototype, self.class_id), generation);
    }
};

/// The selected modules graph creates only the original Realm weak pointer.
/// No async request or other selected consumer takes a BaseObjectPtr to this
/// owner. The weak metadata outlives a collected or Realm-deleted BaseObject.
const PointerData = struct {
    environment: *callbacks.Environment,
    self: ?*BindingData,
    weak_count: c_uint = 0,

    fn releaseWeak(self: *PointerData) void {
        std.debug.assert(self.weak_count != 0);
        self.weak_count -= 1;
        if (self.weak_count != 0 or self.self != null) return;
        self.destroy();
    }
    fn destroy(self: *PointerData) void {
        const environment = self.environment;
        environment.allocator().destroy(self);
        environment.release();
    }
    fn getSlot(raw: *anyopaque) ?*anyopaque {
        const self: *PointerData = @ptrCast(@alignCast(raw));
        return if (self.self) |object| object else null;
    }
    fn releaseSlot(raw: *anyopaque) void {
        const self: *PointerData = @ptrCast(@alignCast(raw));
        self.releaseWeak();
    }
};

pub const BindingData = struct {
    registry: *native.Registry,
    environment: *callbacks.Environment,
    base_entry: native.BaseEntry,
    wrapper: ?c.JSValue,
    // Original BaseObject starts with an independent strong persistent. It
    // becomes weak after the complete derived constructor, before Realm store.
    strong_wrapper: ?c.JSValue,
    pointer_data: ?*PointerData = null,
    retiring: bool = false,
    cache: ?package_cache.Cache = null,

    /// Caller retains the actual target Local throughout AddBindingData.
    /// Registry comes from the already acquired real AsyncWrap realm owner;
    /// no second Registry or cleanup registration is constructed here.
    pub fn create(s: *Scope, shape: TargetTemplate, target: c.JSValue,
        template_owner: c.JSValue) !*BindingData
    {
        const registry = try templates.registry(s.engine, template_owner);
        try s.pending();
        if (c.JS_GetClassID(target) != shape.class_id or
            c.JS_GetOpaque(target, shape.class_id) != null)
            return registry.check(.invalid_wrap_brand);
        const environment = registry.environment;
        const self = try environment.allocator().create(BindingData);
        self.* = .{
            .registry = registry.retain(), .environment = environment,
            .base_entry = .{ .raw = self, .delete_me = deleteBaseEntry },
            .wrapper = target, .strong_wrapper = a.duplicate(s.engine, target),
        };
        _ = c.JS_SetOpaque(target, self);
        // SnapshotableObject initializes its BaseObject before the two native
        // modules members. Its constructor emits no guest operation.
        registry.append(&self.base_entry);
        self.cache = package_cache.Cache.init(s.engine) catch |err| {
            return constructionFailure(self, s.engine, err);
        };
        self.makeWeak() catch |err| {
            return constructionFailure(self, s.engine, err);
        };
        const metadata = self.pointerData() catch |err| {
            return constructionFailure(self, s.engine, err);
        };
        metadata.weak_count += 1;
        defer metadata.releaseWeak(); // local item in Realm::AddBindingData
        if (registry.modules_binding_data) |previous| {
            if (previous.get(previous.raw) != null)
                return registry.check(.binding_data_slot_occupied);
            registry.modules_binding_data = null;
            previous.release(previous.raw);
        }
        // Copy assignment to the actual typed Realm slot owns one weak count.
        metadata.weak_count += 1;
        registry.modules_binding_data = .{
            .raw = metadata, .get = PointerData.getSlot,
            .release = PointerData.releaseSlot,
        };
        return self;
    }
    fn constructionFailure(self: *BindingData, engine: *Engine,
        err: anyerror) anyerror
    {
        // Record a real typed native allocation failure before retiring the
        // partially constructed cache and BaseObject persistent.
        var completion = a.owned.Completion.initVoid(engine, err);
        completion.release(c.pi_js_undefined());
        self.retire(false) catch {};
        completion.finishVoid() catch |selected| return selected;
        unreachable;
    }
    fn pointerData(self: *BindingData) !*PointerData {
        if (self.pointer_data) |metadata| return metadata;
        const metadata = try self.environment.allocator().create(PointerData);
        metadata.* = .{
            .environment = self.environment.retain(), .self = self,
        };
        self.pointer_data = metadata;
        return metadata;
    }
    fn makeWeak(self: *BindingData) !void {
        const engine = try self.environment.requireEngine();
        var s = Scope.init(engine);
        var persistent = self.strong_wrapper orelse return finishEmpty(&s);
        self.strong_wrapper = null;
        // This can run the genuine weak finalizer if the caller violated its
        // Local contract. Do not access self after the persistent is released.
        s.boundary.release(&persistent);
        try finishEmpty(&s);
    }
    pub fn packageCache(self: *BindingData) *package_cache.Cache {
        std.debug.assert(!self.retiring and self.cache != null);
        return &self.cache.?;
    }
    /// The null ErrorContext GetPackageJSON path consumed by CommonJS and
    /// TraverseParent. The caller supplies its native normalized path after
    /// the original permission check; this operation does not repeat either.
    /// ESM base-URL parsing remains in its separate native caller dependency.
    ///
    /// A found entry borrows this actual binding's cache. Retaining the target
    /// in the caller's Scope keeps the native owner alive through fresh result
    /// allocation and an inherited Error.prototype.code setter's reentry.
    pub fn getPackageJSON(self: *BindingData, s: *Scope,
        path: [:0]const u8) !?*const package_cache.Entry
    {
        try s.pending();
        const engine = try self.environment.requireEngine();
        if (engine != s.engine) return error.ActualModulesBindingEngineMismatch;
        const target = self.wrapper orelse return error.ActualModulesBindingRetired;
        _ = try s.own(a.duplicate(engine, target));
        const cache = self.packageCache();
        switch (try cache.get(s, path)) {
            .missing => return null,
            .found => |entry| return entry,
            .invalid => |entry| {
                // Original GetPackageJSON throws while its local Config still
                // owns raw JSON and partial fields. The invalid entry never
                // enters package_configs_; a nested read may publish a valid
                // entry before this independent failed Config is discarded.
                defer cache.discardInvalid(entry);
                _ = try s.own(try package_error.raise(s, cache.allocator(), entry.path, null));
                return error.ActualInvalidPackageConfigThrowRequired;
            },
        }
    }
    /// Owned intrinsic return value of the selected native callback tail.
    /// Missing/read-failed entries return undefined; every success serializes
    /// the cached native Config into a fresh dense six-element Array.
    pub fn serializePackageJSON(self: *BindingData, engine: *Engine,
        path: [:0]const u8) !c.JSValue
    {
        return a.expression(engine, serializePackageBody, .{self, path});
    }
    fn serializePackageBody(s: *Scope, self: *BindingData,
        path: [:0]const u8) !c.JSValue
    {
        const entry = (try self.getPackageJSON(s, path)) orelse
            return c.pi_js_undefined();
        return a.duplicate(s.engine,
            try package_values.serialize(s, entry.config.?, entry.path));
    }
    fn deleteBaseEntry(raw: *anyopaque) !void {
        const self: *BindingData = @ptrCast(@alignCast(raw));
        return self.retire(false);
    }
    fn retire(self: *BindingData, from_gc: bool) !void {
        if (self.retiring) return;
        self.retiring = true;
        const registry = self.registry;
        const environment = self.environment;
        const engine = try environment.requireEngine();
        if (from_gc) {
            std.debug.assert(self.strong_wrapper == null);
            if (self.wrapper) |wrapper| _ = c.JS_SetOpaque(wrapper, null);
            self.wrapper = null;
        }
        var s = Scope.init(engine);
        // Reverse derived-member destruction: json_parser, then package_configs_.
        // Cache uses independently retained native memory, never a JS wrapper.
        if (self.cache) |*cache| {
            cache.deinit();
            self.cache = null;
        }
        registry.unlink(&self.base_entry);
        if (self.pointer_data) |metadata| {
            self.pointer_data = null;
            metadata.self = null;
            if (metadata.weak_count == 0) metadata.destroy();
        }
        if (self.wrapper) |wrapper| _ = c.JS_SetOpaque(wrapper, null);
        self.wrapper = null;
        if (self.strong_wrapper) |value| {
            self.strong_wrapper = null;
            var persistent = value;
            s.boundary.release(&persistent);
        }
        environment.allocator().destroy(self);
        defer registry.release();
        try finishEmpty(&s);
    }
};

/// Realm::GetBindingData copies the weak pointer temporarily and returns the
/// borrowed native object. The real binding cache keeps its target JS edge.
pub fn get(registry: *native.Registry) ?*BindingData {
    const slot = registry.modules_binding_data orelse return null;
    const metadata: *PointerData = @ptrCast(@alignCast(slot.raw));
    metadata.weak_count += 1;
    defer metadata.releaseWeak();
    return metadata.self;
}
fn finalize(_: ?*c.JSRuntime, value: c.JSValue) callconv(.c) void {
    const self: *BindingData = @ptrCast(@alignCast(
        c.JS_GetOpaque(value, c.JS_GetClassID(value)) orelse return));
    const engine = self.environment.requireEngine() catch return;
    self.retire(true) catch |err| { _ = callable.failure(engine, err, 0); };
}
fn finishEmpty(s: *Scope) !void {
    const engine = s.engine;
    const ignored = try s.finish(c.pi_js_undefined());
    engine.freeValue(ignored);
}
