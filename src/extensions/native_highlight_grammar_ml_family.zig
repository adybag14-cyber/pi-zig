//! Actual shared SML/OCaml construction with explicit Source differences.
const b = @import("native_highlight_lazy_batch3_values.zig");
pub fn build(e: *b.Engine, hljs: b.c.JSValue, comptime ocaml: bool) !b.c.JSValue {
    var s: b.Scope = .{ .engine = e };
    defer s.deinit();
    const language = try s.object();
    try s.put(language, "name", try s.text(if (ocaml) "OCaml" else "SML (Standard ML)"));
    try s.put(language, "aliases", try b.list(&s, &.{try s.text("ml")}));
    const words = try s.object();
    try s.put(words, "$pattern", try s.text("[a-z_]\\w*!?"));
    try s.put(words, "keyword", try s.text(if (ocaml) "and as assert asr begin class constraint do done downto else end exception external for fun function functor if in include inherit! inherit initializer land lazy let lor lsl lsr lxor match method!|10 method mod module mutable new object of open! open or private rec sig struct then to try type val! val virtual when while with parser value" else "abstype and andalso as case datatype do else end eqtype exception fn fun functor handle if in include infix infixr let local nonfix of op open orelse raise rec sharing sig signature struct structure then type val with withtype where while"));
    try s.put(words, "built_in", try s.text(if (ocaml) "array bool bytes char exn|5 float int int32 int64 list lazy_t|5 nativeint|5 string unit in_channel out_channel ref" else "array bool char exn int list option order real ref string substring vector unit word"));
    try s.put(words, "literal", try s.text(if (ocaml) "true false" else "true false NONE SOME LESS EQUAL GREATER nil"));
    try s.put(language, "keywords", words);
    try s.put(language, "illegal", try b.rx(&s, "\\/\\/|>>"));
    const literal = try b.mode(&s, "literal");
    try s.put(literal, "begin", if (ocaml) try s.text("\\[(\\|\\|)?\\]|\\(\\)") else try b.rx(&s, "\\[(\\|\\|)?\\]|\\(\\)"));
    try s.put(literal, "relevance", b.c.JS_NewInt32(e.context, 0));
    const comment_function = try s.get(hljs, "COMMENT");
    const options = try s.object();
    try s.put(options, "contains", try b.list(&s, &.{try s.text("self")}));
    const comment = try s.call(comment_function, hljs, &.{ try s.text("\\(\\*"), try s.text("\\*\\)"), options });
    const variable = try b.mode(&s, "symbol");
    try s.put(variable, "begin", try s.text("'[A-Za-z_](?!')[\\w']*"));
    const poly = try b.mode(&s, "type");
    try s.put(poly, "begin", try s.text("`[A-Z][\\w']*"));
    const constructor = try b.mode(&s, "type");
    try s.put(constructor, "begin", try s.text("\\b[A-Z][\\w']*"));
    try s.put(constructor, "relevance", b.c.JS_NewInt32(e.context, 0));
    const guard = try s.object();
    try s.put(guard, "begin", try s.text("[a-z_]\\w*'[\\w']*"));
    if (ocaml) try s.put(guard, "relevance", b.c.JS_NewInt32(e.context, 0));
    const contains = try b.list(&s, &.{ literal, comment, variable, poly, constructor, guard });
    const inherit_apos = try s.get(hljs, "inherit");
    const apos = try s.get(hljs, "APOS_STRING_MODE");
    const apos_changes = try b.mode(&s, "string");
    try s.put(apos_changes, "relevance", b.c.JS_NewInt32(e.context, 0));
    try s.index(contains, 6, try s.call(inherit_apos, hljs, &.{ apos, apos_changes }));
    const inherit_quote = try s.get(hljs, "inherit");
    const quote = try s.get(hljs, "QUOTE_STRING_MODE");
    const quote_changes = try s.object();
    try s.put(quote_changes, "illegal", b.c.pi_js_null());
    try s.index(contains, 7, try s.call(inherit_quote, hljs, &.{ quote, quote_changes }));
    const number = try b.mode(&s, "number");
    try s.put(number, "begin", try s.text("\\b(0[xX][a-fA-F0-9_]+[Lln]?|0[oO][0-7_]+[Lln]?|0[bB][01_]+[Lln]?|[0-9][0-9_]*([Lln]|(\\.[0-9_]*)?([eE][-+]?[0-9_]+)?)?)"));
    try s.put(number, "relevance", b.c.JS_NewInt32(e.context, 0));
    try s.index(contains, 8, number);
    const booster = try s.object();
    try s.put(booster, "begin", try b.rx(&s, if (ocaml) "->" else "[-=]>"));
    try s.index(contains, 9, booster);
    try s.put(language, "contains", contains);
    return b.c.JS_DupValue(e.context, language);
}
