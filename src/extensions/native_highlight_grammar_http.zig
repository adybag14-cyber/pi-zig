//! Actual highlight.js10.7.3 HTTP factory; unqualified source.
const b = @import("native_highlight_lazy_batch3_values.zig");
pub fn create(e: *b.Engine) !b.c.JSValue {
    return b.factory(e, "http", build);
}
pub fn build(e: *b.Engine, hljs: b.c.JSValue) !b.c.JSValue {
    var s: b.Scope = .{ .engine = e };
    defer s.deinit();
    const version = "HTTP/(2|1\\.[01])";
    const header_name = try b.rx(&s, "[A-Za-z][A-Za-z0-9-]*");
    const header = try b.mode(&s, "attribute");
    try s.put(header, "begin", try s.own(try @import("native_highlight_regex.zig").concat(e, try b.list(&s, &.{ try s.text("^"), header_name, try s.text("(?=\\:\\s)") }))));
    const header_starts = try s.object();
    const punctuation = try b.mode(&s, "punctuation");
    try s.put(punctuation, "begin", try b.rx(&s, ": "));
    try s.put(punctuation, "relevance", b.c.JS_NewInt32(e.context, 0));
    const value = try s.object();
    try s.put(value, "end", try s.text("$"));
    try s.put(value, "relevance", b.c.JS_NewInt32(e.context, 0));
    try s.put(punctuation, "starts", value);
    try s.put(header_starts, "contains", try b.list(&s, &.{punctuation}));
    try s.put(header, "starts", header_starts);
    const body = try s.object();
    try s.put(body, "begin", try s.text("\\n\\n"));
    const auto = try s.object();
    try s.put(auto, "subLanguage", try s.array());
    try s.put(auto, "endsWithParent", b.boolean(&s, true));
    try s.put(body, "starts", auto);
    const headers_body = try b.list(&s, &.{ header, body });
    const language = try s.object();
    try s.put(language, "name", try s.text("HTTP"));
    try s.put(language, "aliases", try b.list(&s, &.{try s.text("https")}));
    try s.put(language, "illegal", try b.rx(&s, "\\S"));
    const response = try s.object();
    try s.put(response, "begin", try s.text("^(?=" ++ version ++ " \\d{3})"));
    try s.put(response, "end", try b.rx(&s, "$"));
    const response_meta = try b.mode(&s, "meta");
    try s.put(response_meta, "begin", try s.text(version));
    const status = try b.mode(&s, "number");
    try s.put(status, "begin", try s.text("\\b\\d{3}\\b"));
    try s.put(response, "contains", try b.list(&s, &.{ response_meta, status }));
    const response_starts = try s.object();
    try s.put(response_starts, "end", try b.rx(&s, "\\b\\B"));
    try s.put(response_starts, "illegal", try b.rx(&s, "\\S"));
    try s.put(response_starts, "contains", headers_body);
    try s.put(response, "starts", response_starts);
    const request = try s.object();
    try s.put(request, "begin", try s.text("(?=^[A-Z]+ (.*?) " ++ version ++ "$)"));
    try s.put(request, "end", try b.rx(&s, "$"));
    const target = try b.mode(&s, "string");
    try s.put(target, "begin", try s.text(" "));
    try s.put(target, "end", try s.text(" "));
    try s.put(target, "excludeBegin", b.boolean(&s, true));
    try s.put(target, "excludeEnd", b.boolean(&s, true));
    const request_meta = try b.mode(&s, "meta");
    try s.put(request_meta, "begin", try s.text(version));
    const method = try b.mode(&s, "keyword");
    try s.put(method, "begin", try s.text("[A-Z]+"));
    try s.put(request, "contains", try b.list(&s, &.{ target, request_meta, method }));
    const request_starts = try s.object();
    try s.put(request_starts, "end", try b.rx(&s, "\\b\\B"));
    try s.put(request_starts, "illegal", try b.rx(&s, "\\S"));
    try s.put(request_starts, "contains", headers_body);
    try s.put(request, "starts", request_starts);
    const inherit = try s.get(hljs, "inherit");
    const changes = try s.object();
    try s.put(changes, "relevance", b.c.JS_NewInt32(e.context, 0));
    try s.put(language, "contains", try b.list(&s, &.{ response, request, try s.call(inherit, hljs, &.{ header, changes }) }));
    return b.c.JS_DupValue(e.context, language);
}
