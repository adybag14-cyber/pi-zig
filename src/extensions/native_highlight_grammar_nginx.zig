//! Actual highlight.js 10.7.3 Nginx factory; source-only, unqualified.
const b = @import("native_highlight_lazy_batch3_values.zig");
pub fn create(e: *b.Engine) !b.c.JSValue {
    return b.factory(e, "nginx", build);
}
pub fn build(e: *b.Engine, h: b.c.JSValue) !b.c.JSValue {
    var s: b.Scope = .{ .engine = e };
    defer s.deinit();
    const variable = try b.mode(&s, "variable");
    const v1 = try s.object();
    try s.put(v1, "begin", try b.rx(&s, "\\$\\d+"));
    const v2 = try s.object();
    try s.put(v2, "begin", try b.rx(&s, "\\$\\{"));
    try s.put(v2, "end", try b.rx(&s, "\\}"));
    const v3 = try s.object();
    try s.put(v3, "begin", try s.concat(try b.rx(&s, "[$@]"), try s.get(h, "UNDERSCORE_IDENT_RE")));
    try s.put(variable, "variants", try b.list(&s, &.{ v1, v2, v3 }));
    const default = try s.object();
    try s.put(default, "endsWithParent", b.boolean(&s, true));
    const kw = try s.object();
    try s.put(kw, "$pattern", try s.text("[a-z/_]+"));
    try s.put(kw, "literal", try s.text("on off yes no true false none blocked debug info notice warn error crit select break last permanent redirect kqueue rtsig epoll poll /dev/poll"));
    try s.put(default, "keywords", kw);
    try s.put(default, "relevance", b.c.JS_NewInt32(e.context, 0));
    try s.put(default, "illegal", try s.text("=>"));
    const dc = try b.list(&s, &.{try s.get(h, "HASH_COMMENT_MODE")});
    const str = try b.mode(&s, "string");
    try s.put(str, "contains", try b.list(&s, &.{ try s.get(h, "BACKSLASH_ESCAPE"), variable }));
    const dq = try s.object();
    try s.put(dq, "begin", try b.rx(&s, "\""));
    try s.put(dq, "end", try b.rx(&s, "\""));
    const sq = try s.object();
    try s.put(sq, "begin", try b.rx(&s, "'"));
    try s.put(sq, "end", try b.rx(&s, "'"));
    try s.put(str, "variants", try b.list(&s, &.{ dq, sq }));
    try s.index(dc, 1, str);
    const url = try s.object();
    try s.put(url, "begin", try s.text("([a-z]+):/"));
    try s.put(url, "end", try s.text("\\s"));
    try s.put(url, "endsWithParent", b.boolean(&s, true));
    try s.put(url, "excludeEnd", b.boolean(&s, true));
    try s.put(url, "contains", try b.list(&s, &.{variable}));
    try s.index(dc, 2, url);
    const regex = try b.mode(&s, "regexp");
    try s.put(regex, "contains", try b.list(&s, &.{ try s.get(h, "BACKSLASH_ESCAPE"), variable }));
    const variants = try s.array();
