    try s.put(symbol, "contains", try b.list(&s, &.{try s.get(hljs, "BACKSLASH_ESCAPE")}));
    try s.index(contains, 6, symbol);
    try s.index(contains, 7, try s.get(hljs, "C_LINE_COMMENT_MODE"));
