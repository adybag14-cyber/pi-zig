    try s.put(language, "illegal", try b.rx(&s, "\\/\\*"));
    const keyword = try b.mode(&s, "keyword");
    try s.put(keyword, "begin", try b.rx(&s, "\\b(yield|return|let|do)!"));
    const verbatim = try b.mode(&s, "string");
