fn literal(s: *Scope, pattern: []const u8) !c.JSValue {
    var args = [_]c.JSValue{try s.text(pattern)};
    return s.own(try s.engine.checked(c.JS_CallConstructor(s.engine.context, s.engine.intrinsic_regexp_constructor, args.len, &args)));
}
fn list(s: *Scope, values: []const c.JSValue) !c.JSValue {
    const result = try s.array();
    for (values, 0..) |value, index| try s.index(result, @intCast(index), value);
    return result;
}
fn mode(s: *Scope, class_name: []const u8) !c.JSValue {
    const result = try s.object();
    try s.put(result, "className", try s.text(class_name));
    return result;
}
fn quotedVariants(s: *Scope, delimiter: []const u8, here_begin: []const u8, here_end: []const u8) !c.JSValue {
    const first = try s.object();
    try s.put(first, "begin", try literal(s, delimiter));
    try s.put(first, "end", try literal(s, delimiter));
    const second = try s.object();
    try s.put(second, "begin", try literal(s, here_begin));
    try s.put(second, "end", try literal(s, here_end));
    return list(s, &.{ first, second });
}
pub fn create(engine: *em.Engine) !c.JSValue {
    const Adapter = struct {
        fn invoke(host: *em.Engine, _: c.JSValue, args: []const c.JSValue, _: []const c.JSValue) anyerror!c.JSValue {
            return build(host, if (args.len > 0) args[0] else c.pi_js_undefined());
        }
    };
    return ordinary.create(engine, "powershell", 1, Adapter.invoke, &.{});
}
pub fn build(engine: *em.Engine, hljs: c.JSValue) !c.JSValue {
    var s: Scope = .{ .engine = engine };
    defer s.deinit();
    const types = try s.array();
    inline for (.{ "string", "char", "byte", "int", "long", "bool", "decimal", "single", "double", "DateTime", "xml", "array", "hashtable", "void" }, 0..) |name, index| try s.index(types, index, try s.text(name));
    const keywords = try s.object();
    try s.put(keywords, "$pattern", try literal(&s, "-?[A-z\\.\\-]+\\b"));
    try s.put(keywords, "keyword", try s.text("if else foreach return do while until elseif begin for trap data dynamicparam end break throw param continue finally in switch exit filter try process catch hidden static parameter"));
    try s.put(keywords, "built_in", try s.text("ac asnp cat cd CFS chdir clc clear clhy cli clp cls clv cnsn compare copy cp cpi cpp curl cvpa dbp del diff dir dnsn ebp echo|0 epal epcsv epsn erase etsn exsn fc fhx fl ft fw gal gbp gc gcb gci gcm gcs gdr gerr ghy gi gin gjb gl gm gmo gp gps gpv group gsn gsnp gsv gtz gu gv gwmi h history icm iex ihy ii ipal ipcsv ipmo ipsn irm ise iwmi iwr kill lp ls man md measure mi mount move mp mv nal ndr ni nmo npssc nsn nv ogv oh popd ps pushd pwd r rbp rcjb rcsn rd rdr ren ri rjb rm rmdir rmo rni rnp rp rsn rsnp rujb rv rvpa rwmi sajb sal saps sasv sbp sc scb select set shcm si sl sleep sls sort sp spjb spps spsv start stz sujb sv swmi tee trcm type wget where wjb write"));
    const title_name = try literal(&s, "\\w[\\w\\d]*((-)[\\w\\d]+)*");
    const escape = try s.object();
    try s.put(escape, "begin", try s.text("`[\\s\\S]"));
    try s.put(escape, "relevance", c.JS_NewInt32(engine.context, 0));
    const variable = try mode(&s, "variable");
    const variable_variants = try s.array();
    const bare_dollar = try s.object();
    try s.put(bare_dollar, "begin", try literal(&s, "\\$\\B"));
    try s.index(variable_variants, 0, bare_dollar);
    const this_variable = try mode(&s, "keyword");
    try s.put(this_variable, "begin", try literal(&s, "\\$this"));
    try s.index(variable_variants, 1, this_variable);
    const named = try s.object();
    try s.put(named, "begin", try literal(&s, "\\$[\\w\\d][\\w\\d_:]*"));
    try s.index(variable_variants, 2, named);
    try s.put(variable, "variants", variable_variants);
    const literal_mode = try mode(&s, "literal");
    try s.put(literal_mode, "begin", try literal(&s, "\\$(null|true|false)\\b"));
    const quoted = try mode(&s, "string");
    try s.put(quoted, "variants", try quotedVariants(&s, "\"", "@\"", "^\"@"));
    const unscoped_variable = try mode(&s, "variable");
    try s.put(unscoped_variable, "begin", try literal(&s, "\\$[A-z]"));
    try s.put(unscoped_variable, "end", try literal(&s, "[^A-z]"));
    try s.put(quoted, "contains", try list(&s, &.{ escape, variable, unscoped_variable }));
    const apos = try mode(&s, "string");
    try s.put(apos, "variants", try quotedVariants(&s, "'", "@'", "^'@"));
    const help = try mode(&s, "doctag");
    const help_simple = try s.object();
    try s.put(help_simple, "begin", try literal(&s, "\\.(synopsis|description|example|inputs|outputs|notes|link|component|role|functionality)"));
    const help_parameter = try s.object();
    try s.put(help_parameter, "begin", try literal(&s, "\\.(parameter|forwardhelptargetname|forwardhelpcategory|remotehelprunspace|externalhelp)\\s+\\S+"));
    try s.put(help, "variants", try list(&s, &.{ help_simple, help_parameter }));
    const inherit_comment = try s.get(hljs, "inherit");
    const comment = try s.invoke(hljs, "COMMENT", &.{ c.pi_js_null(), c.pi_js_null() });
    const comment_changes = try s.object();
    const hash_comment = try s.object();
    try s.put(hash_comment, "begin", try literal(&s, "#"));
    try s.put(hash_comment, "end", try literal(&s, "$"));
    const block_comment = try s.object();
    try s.put(block_comment, "begin", try literal(&s, "<#"));
    try s.put(block_comment, "end", try literal(&s, "#>"));
    try s.put(comment_changes, "variants", try list(&s, &.{ hash_comment, block_comment }));
    try s.put(comment_changes, "contains", try list(&s, &.{help}));
    const ps_comment = try s.call(inherit_comment, hljs, &.{ comment, comment_changes });
    const cmdlets = try mode(&s, "built_in");
    const cmdlet = try s.object();
    try s.put(cmdlet, "begin", try s.invoke(try s.text("("), "concat", &.{ try s.text(valid_verbs), try s.text(")+(-)[\\w\\d]+") }));
    try s.put(cmdlets, "variants", try list(&s, &.{cmdlet}));
    const class_mode = try mode(&s, "class");
    try s.put(class_mode, "beginKeywords", try s.text("class enum"));
    try s.put(class_mode, "end", try literal(&s, "\\s*[{]"));
    try s.put(class_mode, "excludeEnd", c.pi_js_bool(engine.context, 1));
    try s.put(class_mode, "relevance", c.JS_NewInt32(engine.context, 0));
    try s.put(class_mode, "contains", try list(&s, &.{try s.get(hljs, "TITLE_MODE")}));
    const function = try mode(&s, "function");
    try s.put(function, "begin", try literal(&s, "function\\s+"));
    try s.put(function, "end", try literal(&s, "\\s*\\{|$"));
    try s.put(function, "excludeEnd", c.pi_js_bool(engine.context, 1));
    try s.put(function, "returnBegin", c.pi_js_bool(engine.context, 1));
    try s.put(function, "relevance", c.JS_NewInt32(engine.context, 0));
    const function_keyword = try s.object();
    try s.put(function_keyword, "begin", try s.text("function"));
    try s.put(function_keyword, "relevance", c.JS_NewInt32(engine.context, 0));
    try s.put(function_keyword, "className", try s.text("keyword"));
    const function_title = try mode(&s, "title");
    try s.put(function_title, "begin", title_name);
    try s.put(function_title, "relevance", c.JS_NewInt32(engine.context, 0));
    const parameters = try s.object();
    try s.put(parameters, "begin", try literal(&s, "\\("));
    try s.put(parameters, "end", try literal(&s, "\\)"));
    try s.put(parameters, "className", try s.text("params"));
    try s.put(parameters, "relevance", c.JS_NewInt32(engine.context, 0));
    try s.put(parameters, "contains", try list(&s, &.{variable}));
    try s.put(function, "contains", try list(&s, &.{ function_keyword, function_title, parameters }));
    const using = try s.object();
    try s.put(using, "begin", try literal(&s, "using\\s"));
    try s.put(using, "end", try literal(&s, "$"));
    try s.put(using, "returnBegin", c.pi_js_bool(engine.context, 1));
    const using_keyword = try mode(&s, "keyword");
    try s.put(using_keyword, "begin", try literal(&s, "(using|assembly|command|module|namespace|type)"));
    try s.put(using, "contains", try list(&s, &.{ quoted, apos, using_keyword }));
    const arguments = try s.object();
    const operator = try mode(&s, "operator");
    try s.put(operator, "begin", try s.invoke(try s.text("("), "concat", &.{ try s.text(comparison_operators), try s.text(")\\b") }));
    const named_argument = try mode(&s, "literal");
    try s.put(named_argument, "begin", try literal(&s, "(-)[\\w\\d]+"));
    try s.put(named_argument, "relevance", c.JS_NewInt32(engine.context, 0));
    try s.put(arguments, "variants", try list(&s, &.{ operator, named_argument }));
    const hash_sign = try mode(&s, "selector-tag");
    try s.put(hash_sign, "begin", try literal(&s, "@\\B"));
    try s.put(hash_sign, "relevance", c.JS_NewInt32(engine.context, 0));
    const methods = try mode(&s, "function");
    try s.put(methods, "begin", try literal(&s, "\\[.*\\]\\s*[\\w]+[ ]??\\("));
    try s.put(methods, "end", try literal(&s, "$"));
    try s.put(methods, "returnBegin", c.pi_js_bool(engine.context, 1));
    try s.put(methods, "relevance", c.JS_NewInt32(engine.context, 0));
    const methods_contains = try s.array();
    const method_keyword = try mode(&s, "keyword");
    const keyword_prefix = try s.text("(");
    const keyword_concat = try s.get(keyword_prefix, "concat");
    const keyword_string = try s.invoke(try s.get(keywords, "keyword"), "toString", &.{});
    const keyword_replace = try s.get(keyword_string, "replace");
    var replace_args = [_]c.JSValue{ try s.text("\\s"), try s.text("g") };
    const whitespace = try s.own(try engine.checked(c.JS_CallConstructor(engine.context, engine.intrinsic_regexp_constructor, replace_args.len, &replace_args)));
    const keyword_alternatives = try s.call(keyword_replace, keyword_string, &.{ whitespace, try s.text("|") });
    try s.put(method_keyword, "begin", try s.call(keyword_concat, keyword_prefix, &.{ keyword_alternatives, try s.text(")\\b") }));
    try s.put(method_keyword, "endsParent", c.pi_js_bool(engine.context, 1));
    try s.put(method_keyword, "relevance", c.JS_NewInt32(engine.context, 0));
    try s.index(methods_contains, 0, method_keyword);
    const inherit_title = try s.get(hljs, "inherit");
    const common_title = try s.get(hljs, "TITLE_MODE");
    const title_changes = try s.object();
    try s.put(title_changes, "endsParent", c.pi_js_bool(engine.context, 1));
    try s.index(methods_contains, 1, try s.call(inherit_title, hljs, &.{ common_title, title_changes }));
    try s.put(methods, "contains", methods_contains);
    const general = try list(&s, &.{ methods, ps_comment, escape, try s.get(hljs, "NUMBER_MODE"), quoted, apos, cmdlets, variable, literal_mode, hash_sign });
    const ps_type = try s.object();
    try s.put(ps_type, "begin", try literal(&s, "\\["));
    try s.put(ps_type, "end", try literal(&s, "\\]"));
    try s.put(ps_type, "excludeBegin", c.pi_js_bool(engine.context, 1));
    try s.put(ps_type, "excludeEnd", c.pi_js_bool(engine.context, 1));
    try s.put(ps_type, "relevance", c.JS_NewInt32(engine.context, 0));
    const empty = try s.array();
    const type_concat = try s.get(empty, "concat");
    const self = try s.text("self");
    const builtin_type = try s.object();
    const type_prefix = try s.text("(");
    const joined_types = try s.invoke(types, "join", &.{try s.text("|")});
    try s.put(builtin_type, "begin", try s.concat(try s.concat(type_prefix, joined_types), try s.text(")")));
    try s.put(builtin_type, "className", try s.text("built_in"));
    try s.put(builtin_type, "relevance", c.JS_NewInt32(engine.context, 0));
    const named_type = try mode(&s, "type");
    try s.put(named_type, "begin", try literal(&s, "[\\.\\w\\d]+"));
    try s.put(named_type, "relevance", c.JS_NewInt32(engine.context, 0));
    try s.put(ps_type, "contains", try s.call(type_concat, empty, &.{ self, general, builtin_type, named_type }));
    _ = try s.invoke(try s.get(methods, "contains"), "unshift", &.{ps_type});
    const language = try s.object();
    try s.put(language, "name", try s.text("PowerShell"));
    try s.put(language, "aliases", try list(&s, &.{ try s.text("ps"), try s.text("ps1") }));
    try s.put(language, "case_insensitive", c.pi_js_bool(engine.context, 1));
    try s.put(language, "keywords", keywords);
    try s.put(language, "contains", try s.invoke(general, "concat", &.{ class_mode, function, using, arguments, ps_type }));
    return c.JS_DupValue(engine.context, language);
}
