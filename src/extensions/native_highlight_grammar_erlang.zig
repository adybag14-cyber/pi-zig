fn directiveWeight(ctx: ?*b.c.JSContext, _: b.c.JSValue, argc: c_int, argv: [*c]b.c.JSValue) callconv(.c) b.c.JSValue {
    const e = b.Engine.fromContext(ctx.?);
    return weighted(e, if (argc > 0) argv[0] else b.c.pi_js_undefined()) catch |err| sdk.fail(e, err);
}
fn weighted(e: *b.Engine, value: b.c.JSValue) !b.c.JSValue {
    var s: b.Scope = .{ .engine = e };
    defer s.deinit();
    return b.c.JS_DupValue(e.context, try s.concat(try s.stringify(value), try s.text("|1.5")));
}
