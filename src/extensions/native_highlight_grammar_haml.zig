//! Actual highlight.js 10.7.3 HAML factory; source-only, unqualified.
const b = @import("native_highlight_lazy_batch3_values.zig");
pub fn create(e: *b.Engine) !b.c.JSValue {
    return b.factory(e, "haml", build);
}
pub fn build(e: *b.Engine, h: b.c.JSValue) !b.c.JSValue {
    var s: b.Scope = .{ .engine = e };
    defer s.deinit();
    const l = try s.object();
    try s.put(l, "name", try s.text("HAML"));
    try s.put(l, "case_insensitive", b.boolean(&s, true));
    const a = try s.array();
    const meta = try b.mode(&s, "meta");
    try s.put(meta, "begin", try s.text("^!!!( (5|1\\.1|Strict|Frameset|Basic|Mobile|RDFa|XML\\b.*))?$"));
    try s.put(meta, "relevance", b.c.JS_NewInt32(e.context, 10));
    try s.index(a, 0, meta);
    const comment = try s.get(h, "COMMENT");
    const cb = try s.text("^\\s*(!=#|=#|-#|/).*$");
    const opt = try s.object();
    try s.put(opt, "relevance", b.c.JS_NewInt32(e.context, 0));
    try s.index(a, 1, try s.call(comment, h, &.{ cb, b.boolean(&s, false), opt }));
    const ruby = try s.object();
    try s.put(ruby, "begin", try s.text("^\\s*(-|=|!=)(?!#)"));
    const rs = try s.object();
    try s.put(rs, "end", try s.text("\\n"));
    try s.put(rs, "subLanguage", try s.text("ruby"));
    try s.put(ruby, "starts", rs);
    try s.index(a, 2, ruby);
    const tag = try b.mode(&s, "tag");
    try s.put(tag, "begin", try s.text("^\\s*%"));
    const tc = try s.array();
    for ([_][2][]const u8{ .{ "selector-tag", "\\w+" }, .{ "selector-id", "#[\\w-]+" }, .{ "selector-class", "\\.[\\w-]+" } }, 0..) |p, i| {
        const m = try b.mode(&s, p[0]);
        try s.put(m, "begin", try s.text(p[1]));
        try s.index(tc, @intCast(i), m);
    }
    const brace = try s.object();
    try s.put(brace, "begin", try b.rx(&s, "\\{\\s*"));
    try s.put(brace, "end", try b.rx(&s, "\\s*\\}"));
    const item = try s.object();
    try s.put(item, "begin", try s.text(":\\w+\\s*=>"));
    try s.put(item, "end", try s.text(",\\s+"));
    try s.put(item, "returnBegin", b.boolean(&s, true));
    try s.put(item, "endsWithParent", b.boolean(&s, true));
    const attr = try b.mode(&s, "attr");
    try s.put(attr, "begin", try s.text(":\\w+"));
    const ic = try b.list(&s, &.{ attr, try s.get(h, "APOS_STRING_MODE"), try s.get(h, "QUOTE_STRING_MODE") });
    const word = try s.object();
    try s.put(word, "begin", try s.text("\\w+"));
    try s.put(word, "relevance", b.c.JS_NewInt32(e.context, 0));
    try s.index(ic, 3, word);
    try s.put(item, "contains", ic);
    try s.put(brace, "contains", try b.list(&s, &.{item}));
    try s.index(tc, 3, brace);
    const paren = try s.object();
    try s.put(paren, "begin", try s.text("\\(\\s*"));
    try s.put(paren, "end", try s.text("\\s*\\)"));
    try s.put(paren, "excludeEnd", b.boolean(&s, true));
    const pi = try s.object();
    try s.put(pi, "begin", try s.text("\\w+\\s*="));
    try s.put(pi, "end", try s.text("\\s+"));
    try s.put(pi, "returnBegin", b.boolean(&s, true));
    try s.put(pi, "endsWithParent", b.boolean(&s, true));
    const pa = try b.mode(&s, "attr");
    try s.put(pa, "begin", try s.text("\\w+"));
    try s.put(pa, "relevance", b.c.JS_NewInt32(e.context, 0));
    const pc = try b.list(&s, &.{ pa, try s.get(h, "APOS_STRING_MODE"), try s.get(h, "QUOTE_STRING_MODE") });
    const pw = try s.object();
    try s.put(pw, "begin", try s.text("\\w+"));
    try s.put(pw, "relevance", b.c.JS_NewInt32(e.context, 0));
    try s.index(pc, 3, pw);
    try s.put(pi, "contains", pc);
    try s.put(paren, "contains", try b.list(&s, &.{pi}));
    try s.index(tc, 4, paren);
    try s.put(tag, "contains", tc);
    try s.index(a, 3, tag);
    const eq = try s.object();
    try s.put(eq, "begin", try s.text("^\\s*[=~]\\s*"));
    try s.index(a, 4, eq);
    const subst = try s.object();
    try s.put(subst, "begin", try b.rx(&s, "#\\{"));
    const ss = try s.object();
    try s.put(ss, "end", try b.rx(&s, "\\}"));
    try s.put(ss, "subLanguage", try s.text("ruby"));
    try s.put(subst, "starts", ss);
    try s.index(a, 5, subst);
    try s.put(l, "contains", a);
    return b.c.JS_DupValue(e.context, l);
}
